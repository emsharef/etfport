import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

HERE = Path(__file__).resolve().parent
load = lambda n: json.load(open(HERE / f"summary_{n}.json"))["results"]
TAUS = (0.1, 1.0, 10.0)
NAMES = ["F1", "F2", "F3", "E1", "E2"]


def readings(C, tau):
    """The registered readings Q1-Q5 at tolerance tau (bp of W_0), in-scope cases."""
    r = dict(Q1_049=0, Q1_115=0, Q1_band_only=0, Q2_alloc=0, Q2_obj=0, Q3=0, Q4=0, Q5_myopic=0, Q5_plan=0, Q5_funding_slack=0)
    for c in C:
        bm, bs = c["bounds_myopic"], c["bounds_plan"]; Lm, Ls = c["myopic"]["loss_bp"], c["plan"]["loss_bp"]
        b049 = bm["band049_bp"] + bm["tail_bp"]; b115m = bm["band115_bp"] + bm["tail_bp"]; b115s = bs["band115_bp"] + bs["tail_bp"]
        r["Q1_049"] += b049 <= tau; r["Q1_115"] += b115m <= tau; r["Q1_band_only"] += bm["band115_bp"] <= tau
        dx = np.max(np.abs(np.array(c["dynamic"]["x"]) - np.array(c["myopic"]["x"])))
        r["Q2_alloc"] += dx > 0.01; r["Q2_obj"] += Lm > tau
        r["Q3"] += Ls > tau
        r["Q4"] += (min(b115m, b049) > tau and b115s > tau and min(Lm, Ls) < tau)
        r["Q5_myopic"] += (not bm["test_pass"]["0.0"]) and Lm < tau; r["Q5_plan"] += (not bs["test_pass"]["0.0"]) and Ls < tau
        r["Q5_funding_slack"] += (not bm["test_pass"]["0.0"]) and c["dynamic_tomorrow_binding_states"] == 0
    return r


def tables(C, O, diag, worked, larger):
    L = ["# Experiment 058: tables (generated by report.py)", "", "All losses, bound terms and costs in bp of initial wealth; every input assumed (rule 22).", ""]
    L += ["## Readings Q1-Q5 (78 in-scope cases)", "", "| reading | tau = 0.1 bp | tau = 1 bp | tau = 10 bp |", "|---|---|---|---|"]
    R = {t: readings(C, t) for t in TAUS}
    lab = dict(Q1_049="Q1: claim 049's bound (band + tail) at the one-review root <= tau", Q1_115="Q1: claim 115's bound at the one-review root <= tau",
               Q1_band_only="(the band term alone <= tau)", Q2_alloc="Q2: the dynamic root differs from the one-review root by > 0.01 of W_0 (tau-free)",
               Q2_obj="Q2: one-review loss > tau", Q3="Q3: policy 2's loss > tau", Q4="Q4: both policies' bounds > tau while a policy's loss < tau",
               Q5_myopic="Q5: test fails at eps = 0 at the one-review root while its loss < tau", Q5_plan="Q5: the same at policy 2's root",
               Q5_funding_slack="Q5: test fails at the one-review root while the dynamic tomorrow budget is slack in every state (tau-free)")
    for k, v in lab.items():
        L.append(f"| {v} | " + " | ".join(str(R[t][k]) for t in TAUS) + " |")
    L += ["", "## Every registered case", "",
          "| regime | start | setting | loss one-review | loss policy 2 | 049 band | 049 input-only band | 115 band (one-review root) | 115 band (policy 2 root) | tail (one-review) | tail (policy 2) | eps one-review / policy 2 | dynamic tomorrow: binding states of 140 | max root difference |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for c in C + O:
        bm, bs = c["bounds_myopic"], c["bounds_plan"]; dx = np.max(np.abs(np.array(c["dynamic"]["x"]) - np.array(c["myopic"]["x"])))
        sc = "" if c["in_scope"] else " (out of scope: bounds not applicable)"
        L.append(f"| {c['regime'].split('-')[0]} | {c['start']} | {c['setting']}{sc} | {c['myopic']['loss_bp']:.3f} | {c['plan']['loss_bp']:.3f} | {bm['band049_bp']:.3f} | "
                 f"{bm['input_band049_bp']:.2f} | {bm['band115_bp']:.3f} | {bs['band115_bp']:.1e} | {bm['tail_bp']:.1f} | {bs['tail_bp']:.1f} | {bm['eps']:.2f} / {bs['eps']:.2f} | "
                 f"{c['dynamic_tomorrow_binding_states']} | {dx:.4f} |")
    L += ["", "## Deviation 1: claim 049's need against what the relaxed tomorrow actually buys (78 in-scope cases)", "",
          "| root | E[purchases]/E[need]: median [max] | max purchases / max need: median | cases where the relaxed tomorrow is short in some state |", "|---|---|---|---|"]
    for k in ("myopic", "plan"):
        r = np.array([d[k]["E_relaxed_purchases"] / d[k]["E_need"] for d in diag]); m = np.array([d[k]["max_relaxed_purchases"] / d[k]["max_need"] for d in diag])
        L.append(f"| {k} | {np.median(r):.3f} [{r.max():.3f}] | {np.median(m):.3f} | {sum(d[k]['relaxed_shortfall_states'] > 0 for d in diag)} |")
    for law, w in worked.items():
        L += ["", f"## The worked example ({law} law, {w['states']} states)", "",
              "| policy | " + " | ".join(NAMES) + " | cash | today's cost | E tomorrow's cost | loss |", "|---|" + "---|" * 9]
        L.append("| start | 0.100 | 0.100 | 0.050 | 0.400 | 0.200 | 0.150 | - | - | - |")
        for p in ("myopic", "plan", "dynamic"):
            x = w[p]["x"]; L.append(f"| {p} | " + " | ".join(f"{v:.3f}" for v in x) + f" | {w[p]['cash']:.3f} | {w[p]['cost0_bp']:.2f} | {w[p]['E_cost1_bp']:.2f} | {w[p]['loss_bp']:.3f} |")
        bm, bs = w["bounds_myopic"], w["bounds_plan"]
        L += ["", f"Bound terms: claim 049 band {bm['band049_bp']:.2f}, claim 115 band {bm['band115_bp']:.2f} (one-review root) and {bs['band115_bp']:.1e} (policy 2's root); "
              f"tail {bm['tail_bp']:.1f} and {bs['tail_bp']:.1f}; eps {bm['eps']:.2f} and {bs['eps']:.2f}; planned purchase PP {bm['PP']:.3f} and {bs['PP']:.3f}; "
              f"the dynamic tomorrow's budget binds in {w['dynamic_tomorrow_binding_states']} of {w['states']} states. Runtime: {w['wall_s']:.0f} s in all."]
    for k, g in larger.items():
        L += ["", f"## The larger menu ({k}: funds x ETFs x factors, axis law, {g['states']} states)", "",
              f"Losses: one-review {g['myopic']['loss_bp']:.3f} bp, policy 2 {g['plan']['loss_bp']:.3f} bp. Bound terms at the one-review root: 049 band {g['bounds_myopic']['band049_bp']:.2f}, "
              f"115 band {g['bounds_myopic']['band115_bp']:.2f}, tail {g['bounds_myopic']['tail_bp']:.1f} (eps {g['bounds_myopic']['eps']:.2f}); in scope: {g['in_scope']}. "
              f"Accuracy: J - V {g['accuracy']['J_dyn_minus_V']:.1e}, relaxed node error {g['accuracy']['relaxed_node_err']:.1e}, funded cash >= {min(v for k2, v in g['accuracy'].items() if k2.startswith('min_cash')):.1e}. "
              f"Runtime: {g['wall_s']:.0f} s in all; " + ", ".join(f"{k2} {v:.1f} s" for k2, v in g["timing_s"].items()) + "."]
    (HERE / "tables.md").write_text("\n".join(L) + "\n")


def fig_allocations(w):
    fig, ax = plt.subplots(figsize=(7, 3.6)); labels = NAMES + ["cash"]
    rows = [("start", [0.10, 0.10, 0.05, 0.40, 0.20, 0.15])] + [(p, w[p]["x"] + [w[p]["cash"]]) for p in ("myopic", "plan", "dynamic")]
    names = dict(start="start", myopic="1: repeated one-review", plan="2: plan without tomorrow's budget", dynamic="3: funded two-review optimum")
    width = 0.2
    for j, (p, v) in enumerate(rows):
        ax.bar(np.arange(6) + (j - 1.5) * width, v, width, label=names[p])
    ax.set_xticks(np.arange(6)); ax.set_xticklabels(labels); ax.set_ylabel("holding (fraction of initial wealth)")
    ax.set_title("Worked example: today's holdings by policy (fixed-income-style, rebalancing, predictable alpha rise; assumed inputs)", fontsize=8)
    ax.legend(fontsize=7); fig.tight_layout(); fig.savefig(HERE / "fig_allocations.png", dpi=140)


def fig_tomorrow(w):
    q = np.array(w["state_probs"]); fig, ax = plt.subplots(1, 2, figsize=(10, 3.8))
    for j, p in enumerate(("myopic", "dynamic")):
        tr = np.array([s["trade"] for s in w[p]["by_state"]]); buy = np.maximum(tr, 0).sum(1); sell = np.minimum(tr, 0).sum(1)
        o = np.argsort(buy - sell)
        ax[0].plot(np.arange(len(o)), (buy)[o], lw=1, label=f"{p}: purchases"); ax[0].plot(np.arange(len(o)), (sell)[o], lw=1, ls="--", label=f"{p}: sales")
    ax[0].set_xlabel("tomorrow's states, sorted"); ax[0].set_ylabel("trade (fraction of W_0)"); ax[0].legend(fontsize=7)
    ax[0].set_title("Tomorrow's funded trades by state", fontsize=8)
    b = w["bounds_myopic"]["by_state"]; need = np.array(b["need"]); liq = np.array(b["liq"])
    tr = np.array([s["trade"] for s in w["myopic"]["by_state"]]); act = np.maximum(tr, 0).sum(1)
    o = np.argsort(need)
    ax[1].plot(need[o], label="claim 049's need (solo targets)"); ax[1].plot(liq[o], label="liquid reserve"); ax[1].plot(act[o], label="actual funded purchases (one-review)")
    ax[1].set_xlabel("tomorrow's states, sorted by need"); ax[1].legend(fontsize=7); ax[1].set_title("At the one-review root: need, reserve and what is bought", fontsize=8)
    fig.tight_layout(); fig.savefig(HERE / "fig_tomorrow.png", dpi=140)


def fig_losses(C):
    fig, ax = plt.subplots(1, 2, figsize=(10, 4))
    Lm = np.array([max(c["myopic"]["loss_bp"], 1e-4) for c in C]); Ls = np.array([max(c["plan"]["loss_bp"], 1e-4) for c in C])
    b049 = np.array([c["bounds_myopic"]["band049_bp"] for c in C]); b115 = np.array([max(c["bounds_myopic"]["band115_bp"], 1e-4) for c in C])
    tm = np.array([c["bounds_myopic"]["tail_bp"] for c in C]); ts = np.array([c["bounds_plan"]["tail_bp"] for c in C])
    ax[0].scatter(Lm, b049, s=10, label="claim 049 band term"); ax[0].scatter(Lm, b115, s=10, label="claim 115 band term"); ax[0].scatter(Lm, tm, s=10, label="tail term")
    ax[1].scatter(Ls, ts, s=10, c="C2", label="tail term (policy 2's bound)")
    for a, t in zip(ax, ("one-review policy", "policy 2 (plan without tomorrow's budget)")):
        a.set_xscale("log"); a.set_yscale("log"); lim = [1e-4, 1e3]; a.plot(lim, lim, color="grey", lw=0.6); a.set_xlim(lim); a.set_ylim(lim)
        a.set_xlabel(f"actual loss, {t} (bp)"); a.set_ylabel("bound term (bp)"); a.legend(fontsize=7)
    fig.suptitle("Actual losses against the bound terms (78 in-scope cases; terms of an upper bound, not a decomposition; losses below 1e-4 bp shown at 1e-4)", fontsize=8)
    fig.tight_layout(); fig.savefig(HERE / "fig_losses_bounds.png", dpi=140)


def main():
    D = load("design"); C = [c for c in D if c["in_scope"]]; O = [c for c in D if not c["in_scope"]]
    diag = load("diag"); worked = load("worked") if (HERE / "summary_worked.json").exists() else {}
    larger = load("larger") if (HERE / "summary_larger.json").exists() else {}
    tables(C, O, diag, worked, larger)
    if worked:
        fig_allocations(worked["axis"]); fig_tomorrow(worked["axis"])
    fig_losses(C)
    for t in TAUS:
        print(t, readings(C, t))


if __name__ == "__main__":
    main()
